const { chromium } = require('playwright')
const assert=require('node:assert/strict')
const path=require('node:path')
async function main(){
  const browser=await chromium.launch({headless:true,...(process.env.LAYOUT_BROWSER?{executablePath:process.env.LAYOUT_BROWSER}:{channel:"msedge"})})
  try{
    const page=await browser.newPage({ignoreHTTPSErrors:true,viewport:{width:1440,height:1000}})
    const errors=[]; page.on('pageerror',e=>errors.push(e.message))
    const base=(process.env.ADMIN_BASE_URL||'http://127.0.0.1:10030').replace(/\/+$/,'')
    const adminScript=await (await page.request.get(base+'/admin/static/app.js')).text()
    assert.equal(adminScript.includes('setInterval(autoRefresh,12000)'),true,'monitor auto refresh contract changed')
    await page.goto(base+'/admin/')
    await page.locator('#login').waitFor({state:'visible'})
    assert.equal(await page.locator('#refresh').textContent(),'手动刷新')
    await page.locator('#username').fill(process.env.ADMIN_USERNAME||'admin')
    await page.locator('#password').fill(process.env.ADMIN_TEST_PASSWORD)
    await page.getByRole('button',{name:'登录',exact:true}).click()
    await page.locator('.preview video').waitFor()
    assert.equal(await page.locator('#navigation button').count(),4)
    await page.screenshot({path:path.join(process.env.TEMP,'phase2-admin-desktop.png'),fullPage:true})
    assert(await page.locator('tbody tr').count()>0)
    await page.getByRole('button',{name:'多选操作',exact:true}).click()
    await page.locator('.selection-bar').waitFor()
    assert.equal(await page.locator('.batch-heat').count(),1)
    assert.equal(await page.getByRole('button',{name:'应用热度',exact:true}).count(),1)
    await page.locator('tbody tr').first().locator('input[type=checkbox]').check()
    assert.equal(await page.locator('.selection-bar').textContent().then(t=>t.includes('已选本页 1 个')),true)
    await page.screenshot({path:path.join(process.env.TEMP,'phase2-admin-batch.png'),fullPage:true})
    await page.getByRole('button',{name:'退出多选',exact:true}).click()
    await page.getByRole('button',{name:'交易与退款'}).click()
    await page.locator('.metrics').waitFor()
    await page.locator('.filter-bar').waitFor()
    await page.screenshot({path:path.join(process.env.TEMP,'phase2-admin-transactions.png'),fullPage:true})
    await page.getByRole('button',{name:'运营监控'}).click()
    await page.locator('.module-tabs button').filter({hasText:'制作任务'}).click()
    await page.locator('.module-tabs button.active').filter({hasText:'制作任务'}).waitFor()
    await page.locator('.toolbar').waitFor()
    await page.screenshot({path:path.join(process.env.TEMP,'phase2-admin-monitor.png'),fullPage:true})
    await page.getByRole('button',{name:'日志中心'}).click()
    await page.locator('.module-tabs button').filter({hasText:'管理员日志'}).click()
    await page.locator('.module-tabs button.active').filter({hasText:'管理员日志'}).waitFor()
    await page.locator('tbody tr').first().waitFor()
    await page.locator('.module-tabs button').filter({hasText:'程序日志'}).click()
    await page.locator('.module-tabs button.active').filter({hasText:'程序日志'}).waitFor()
    await page.locator('.filter-bar').waitFor()
    await page.locator('.module-tabs button').filter({hasText:'服务日志'}).click()
    await page.locator('.module-tabs button.active').filter({hasText:'服务日志'}).waitFor()
    await page.locator('.filter-bar').waitFor()
    await page.screenshot({path:path.join(process.env.TEMP,'phase2-admin-logs.png'),fullPage:true})
    await page.getByRole('button',{name:'模板中心'}).click()
    await page.locator('.preview video').waitFor()
    await page.locator('#upload-open').click()
    await page.locator('#upload-dialog').waitFor({state:'visible'})
    assert.equal(await page.locator('#upload-publish').count(),0)
    await page.getByRole('button',{name:'关闭',exact:true}).click()
    for(const width of [1024,390]){
      await page.setViewportSize({width,height:900})
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'page overflow at '+width)
      if(width===390){
        const navWidths=await page.locator('#navigation button').evaluateAll(items=>items.map(item=>item.getBoundingClientRect().width))
        assert(navWidths.every(value=>value>200),'mobile navigation must stay single-column: '+JSON.stringify(navWidths))
      }
    }
    await page.screenshot({path:path.join(process.env.TEMP,'phase2-admin-mobile.png'),fullPage:true})
    assert.deepEqual(errors,[])
    await page.getByRole('button',{name:'退出登录'}).click()
    await page.locator('#login').waitFor({state:'visible'})
    console.log('PASS: admin login, four modules, transactions, monitor tabs, three log types, batch heat, ZIP dialog, responsive; no browser errors')
  }finally{await browser.close()}
}
main().catch(error=>{console.error(error.stack||error.message);process.exitCode=1})

